#!/usr/bin/env python3
"""mkimage.py -- turn an eclipse-cc .simh user program into a C header the
kernel can load into a fresh address space (kernel/proc.c proc_create).

usage: mkimage.py prog.simh NAME > NAME.h

Emits NAME_words[] (dense, logical addresses base..end), NAME_nwords,
NAME_base and NAME_stacktop. The stack top is recovered from the
program's own first instruction: EclipseAsmPrinter emits `_start:` as
`LDA 0,_STACKTOP` at org 050, i.e. the word at 050 is 020000|addr with
addr = _STACKTOP's page-zero location; that location holds the value
reorder_asm.py's fix_stack_pointer chose. Checked, not assumed.
"""
import re, sys

path, name = sys.argv[1], sys.argv[2]
mem = {}
for line in open(path):
    m = re.match(r'^dep\s+([0-7]+)\s+([0-7]+)\s*$', line)
    if m:
        mem[int(m.group(1), 8)] = int(m.group(2), 8)
if not mem:
    sys.exit(f'{path}: no dep lines')
base, end = min(mem), max(mem)
if base != 0o50:
    sys.exit(f'{path}: expected program origin 050, got {base:o}')
lda = mem[0o50]
if lda & 0o177400 != 0o020000:
    sys.exit(f'{path}: word at 050 is {lda:o}, not LDA 0,<page-zero addr>')
stacktop = mem[lda & 0o377]
if stacktop <= end:
    sys.exit(f'{path}: _STACKTOP {stacktop:o} not above image end {end:o}')
words = [mem.get(a, 0) for a in range(base, end + 1)]
print(f'/* generated by kernel/mkimage.py from {path} -- do not edit */')
print(f'#define {name}_base 0{base:o}')
print(f'#define {name}_nwords {len(words)}')
print(f'#define {name}_stacktop 0{stacktop:o}')
print(f'const unsigned int {name}_words[{len(words)}] = {{')
for i in range(0, len(words), 8):
    print('  ' + ', '.join(f'0{w:o}' for w in words[i:i + 8]) + ',')
print('};')
